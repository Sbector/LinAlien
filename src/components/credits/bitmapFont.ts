function parse(art: string): number[] {
  return art.split('|').map((row) => {
    let bits = 0;
    for (let i = 0; i < 5; i += 1) {
      if (row[i] === '#') bits |= 16 >> i;
    }
    return bits;
  });
}

export const FONT: Record<string, number[]> = Object.fromEntries(
  Object.entries(ART).map(([glyph, art]) => [glyph, parse(art)]),
);

export const GLYPH_H = 7;
export const GLYPH_ADVANCE = 6;

export function textWidth(text: string, size = 1): number {
  const count = Array.from(text).length;
  return count > 0 ? count * GLYPH_ADVANCE * size - size : 0;
}

export function wrapText(text: string, maxWidth: number, size = 1): string[] {
  const words = text.split(' ');
  const lines: string[] = [];
  let line = '';
  for (const word of words) {
    const candidate = line ? `${line} ${word}` : word;
    if (!line || textWidth(candidate, size) <= maxWidth) {
      line = candidate;
    } else {
      lines.push(line);
      line = word;
    }
  }
  if (line) lines.push(line);
  return lines;
}

export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  size = 1,
): void {
  ctx.fillStyle = color;
  let cursor = x;
  for (const char of text) {
    const rows = FONT[char] ?? FONT['?'];
    for (let r = 0; r < GLYPH_H; r += 1) {
      const bits = rows[r];
      if (!bits) continue;
      for (let c = 0; c < 5; c += 1) {
        if (bits & (16 >> c)) {
          ctx.fillRect(cursor + c * size, y + r * size, size, size);
        }
      }
    }
    cursor += GLYPH_ADVANCE * size;
  }
}
